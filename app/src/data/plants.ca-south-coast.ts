// Seed dataset — southern California west of the desert: the coastal plain,
// inland valleys and foothills from Santa Barbara to the Mexican border, using
// the Los Angeles–San Diego lowlands (USDA zones 9b–10b) as the reference. It is
// the first California region, and the start of covering the whole West Coast
// (see docs/west-coast-plan.md for the other six).
//
// The one thing to understand about this list before reading a row: **the
// summer is the dry season**. Rain falls between November and April and then
// essentially stops for five months. Almost every plant here is adapted to that
// — many go dormant, drop leaves or die back in July rather than in December —
// and the commonest way to kill one is to water it through a hot summer, which
// rots the roots of a chaparral shrub in a season. Where that applies, the care
// note says so plainly, because it is the opposite of what a gardener who
// learned anywhere else has been taught.
//
// Numbers and their provenance:
//  - hostLepCount: genus-level count of Lepidoptera species that use the plant
//    as a larval host. There is no western equivalent of the eastern
//    Tallamy/NWF tables at species resolution, so — exactly as in the Pacific
//    Northwest file — these are rounded, honest genus-level *estimates*,
//    anchored on the eastern figures and discounted for the West's smaller
//    moth fauna. Oak, willow, cottonwood and cherry still lead. Each row says
//    so in `basis` and records it in `hostCountFrom`.
//  - size arrays: typical growth on an average cismontane site with no summer
//    irrigation; mature* is the honest eventual ceiling, which for chaparral
//    shrubs is usually far larger — and reached far faster — than a nursery
//    label suggests.
//  - other scores (0–100): informed estimates from regional floras and
//    conservation sources — the Jepson eFlora, Calflora, Calscape (CNPS), the
//    US Forest Service FEIS fire-ecology database, Xerces Society western
//    lists, and USDA PLANTS. See DATA_SOURCES.md for licensing of each.
//
