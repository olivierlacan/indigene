// Seed dataset — Central Texas, using Austin (USDA zone 8b) as the reference,
// with Dallas–Fort Worth (8a) at the cold end and San Antonio (9a) at the warm
// one. Three EPA ecoregions share this list because they share its problem: the
// limestone Edwards Plateau (30) with its thin caliche over rock, the deep black
// shrink-swell clay of the Texas Blackland Prairies (32), and the Cross Timbers
// (29), whose Grand Prairie limestone carries Fort Worth. Summers are long, hot
// and droughty; the ground is alkaline almost everywhere; and the deer eat
// anything they are not told to avoid — so every row says whether they do.
//
// Numbers and their provenance:
//  - hostLepCount: genus-level count of Lepidoptera species that use the plant
//    as a larval host, from Tallamy / NWF Native Plant Finder. Those figures were
//    counted for the eastern US and are *carried* to Texas here, so every row
//    records them as `estimated` and its `basis` says so. A genus with no
//    published figure gets `null` — not counted — rather than a guess, and never
//    0, which would claim that nothing eats it.
//  - size arrays: typical field growth on an average Austin site — which grows
//    slower than the same plant in the East, for want of water; mature*Ft is the
//    honest eventual ceiling.
//  - other scores (0–100): informed estimates from the Lady Bird Johnson
//    Wildflower Center (Austin), USDA PLANTS, Texas A&M AgriLife Extension, the
//    Native Plant Society of Texas and Xerces. See DATA_SOURCES.md for licensing.
//  - native status: USDA PLANTS (native to the lower 48, recorded in Texas) and
//    the Wildflower Center's own range notes, checked against Kew's WCVP for
//    Texas (TDWG:TEX) by `npm run native:check -- --region central-texas`.
//
