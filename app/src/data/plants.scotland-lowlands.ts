// Seed dataset — the Scottish Lowlands: the Central Belt from Glasgow and the
// Clyde to Edinburgh and the Forth, with Fife and Tayside to the north, Ayrshire
// and Galloway to the south-west and the Borders to the south-east (roughly
// USDA zones 8a–9a). The EEA puts it in the *Atlantic* biogeographical region,
// like Ireland and Atlantic France, but it is cooler than either, with shorter
// summers and later springs.
//
// **This list was built for Scotland, not borrowed from Ireland.** Many species
// are shared, but every row here was checked separately against Scottish
// records, and some answers differ. Scots pine is Scotland's national tree, and
// in the lowlands it is planted, not native (see below). Beech, sycamore and
// yew grow everywhere here and are introductions or doubtful, so they are left
// out.
//
// Numbers and their provenance — same honesty bar as every other region file:
//  - **Native status** comes from the BSBI's Plant Atlas 2020, which records for
//    every species and every 10 km square of Britain whether the plant there is
//    native or introduced. `npm run bsbi:check -- --region scotland-lowlands`
//    counts the squares inside this region's box where each row was recorded
//    as native since 2000, and the count is quoted in each row's `basis`. A row
//    ships only if it is native in at least ten of the box's ~420 squares.
//    Kew's WCVP (`native:check`, TDWG:GRB) is a floor check under it: it
//    answers for Great Britain as a whole, so it can rule a plant out but not
//    in.
//  - **Widely planted trees are the exception the atlas admits to.** For rowan,
//    holly, ivy, gean and pedunculate oak, BSBI maps where the plant grows without
//    saying whether each tree was planted, because nobody can tell. Those rows
//    say so: they cite presence in the box, WCVP's native verdict for Britain,
//    and Scotland's native woodland record, and nothing stronger.
//  - **hostLepCount** is a genus-level count of Lepidoptera (butterflies and
//    moths) that use the plant as a larval host — **computed, not estimated**,
//    from the Gaytán et al. 2026 European Lepidoptera–plant matrix (CC-BY 4.0,
//    doi:10.1002/ece3.73004), counted for the *Oceanic temperate* zone and only
//    for relatives native to it. Regenerate with
//    `npm run host-counts -- --region scotland-lowlands`.
//  - **size arrays**: typical field growth on an average lowland Scottish site,
//    which is cooler and windier than most of Britain, so trees put on a little
//    less each year than the same species further south. Feet, like every other
//    region.
//  - **bloom months** are a week or three later than southern England's.
//  - **other scores (0–100)**: informed estimates from Scottish and British
//    sources — NatureScot, the Woodland Trust, Trees for Life, Plantlife
//    Scotland and the RHS "Plants for Pollinators" list. Estimates, the way they
//    are everywhere else.
//
// **The people of a place name its plants too.** Where a plant has a common
// Scottish Gaelic or Scots name, the row gives it.
//
// **Deliberately absent:**
//  - *Scots pine* (Pinus sylvestris). The atlas records it as native in only 7
//    of this box's squares, all at the Highland edge, and as planted in 382.
//    Its native pinewoods are a Highland list's job.
//  - *Ash and wych elm*, for the reason Ireland gives: dieback and Dutch elm
//    disease have killed most of them, and recommending one for a garden now is
//    bad advice.
//  - *Beech, sycamore, yew, white dead-nettle, sweet cicely*: all common here,
//    all recorded by the atlas as introduced (or, for yew, of doubtful status)
//    in these squares.
//
