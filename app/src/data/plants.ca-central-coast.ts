// Seed dataset — the central California coast: the coast ranges and the valleys
// between them, from Sonoma and Marin south through the Bay Area to Big Sur, and
// inland to the crest above the Central Valley. San Francisco Bay (USDA zones
// 9a–10a) is the reference.
//
// **Two things decide almost every row in this list, and they pull in opposite
// directions.**
//
// The first is the one the southern California list opens with: *the summer is
// the dry season*. Rain falls November to April and then stops. Watering a
// chaparral shrub through a hot summer rots it, which is the opposite of what a
// gardener trained anywhere else expects.
//
// The second is local and it is why this is its own region: **the fog.** From
// June to August a marine layer sits on the coastal strip, and inside it the
// summer is cool, grey and damp — redwood, huckleberry, salal and sword fern
// live on what condenses out of the air. Twenty miles inland, over one ridge,
// the same summer is 95 °F and cloudless, and those plants die without a hose.
// The fog line is not marked on any map a gardener owns, but it is the single
// most useful thing to know about a spot here. Where a row's advice changes
// across it, the care note says so.
//
// Numbers and their provenance:
//  - hostLepCount: genus-level count of Lepidoptera species that use the plant
//    as a larval host. There is no western equivalent of the eastern
//    Tallamy/NWF tables at species resolution, so — exactly as in the Pacific
//    Northwest and southern California files — these are rounded, honest
//    genus-level *estimates*, anchored on the eastern figures and discounted for
//    the West's smaller moth fauna. Oak, willow, cherry and Ceanothus lead. Each
//    row says so in `basis` and records it in `hostCountFrom`.
//  - size arrays: typical growth on an average site with no summer irrigation
//    unless the care note says otherwise; mature* is the honest eventual
//    ceiling, which for a coast redwood or a valley oak is far beyond what any
//    nursery label admits.
//  - other scores (0–100): informed estimates from regional floras and
//    conservation sources — the Jepson eFlora, Calflora, Calscape (CNPS), the
//    US Forest Service FEIS fire-ecology database, Xerces Society western
//    lists, and USDA PLANTS. See DATA_SOURCES.md for licensing of each.
//
