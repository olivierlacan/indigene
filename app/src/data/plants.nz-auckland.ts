// Seed dataset — Auckland & Northland: the northern North Island of New
// Zealand, from Cape Reinga to the Coromandel, using Auckland as the reference
// (roughly USDA zones 9b–10b; frost is light and rare near the coast, harder in
// inland hollows). The first region south of the equator, so **every month in
// this file is a southern month**: bloom in December is midsummer, and "sow in
// autumn" means March–May.
//
// Numbers and their provenance — same honesty bar as every other region file:
//  - **Native status** is asserted from Kew's World Checklist of Vascular Plants
//    (WCVP, CC BY 4.0) for the North Island (`TDWG:NZN`), the way Ireland's is
//    for `TDWG:IRE`. Every row was checked against it (2026-09-24); several
//    appear there under newer names — *Phormium colensoi*, *Alsophila
//    dealbata*, *Sphaeropteris medullaris*, *Didymocheton spectabilis*,
//    *Goodenia radicans* — and keep here the name a New Zealand nursery label
//    carries. The North Island is a coarse area, so each `nativeNote` also says
//    where on it the plant grows wild; every plant here does so north of the
//    Waikato.
//  - **hostLepCount is null on every row: not yet counted.** No source in hand
//    gives a citable count of the moths and butterflies that raise their
//    caterpillars on New Zealand plants (Plant-SyNZ and the NHM's HOSTS
//    database are the candidates; see docs/southern-hemisphere-plan.md). The
//    app says "not counted yet" and ranks on the other scores, rather than
//    printing a 0 that would read as "feeds nothing". `keystone` is false for
//    the same reason: it is a claim about host counts.
//  - **size arrays**: typical growth on an average Auckland site, in feet like
//    every other region. mature*Ft is the honest eventual ceiling.
//  - **other scores (0–100)**: informed estimates from the New Zealand Plant
//    Conservation Network's species pages, Auckland Council and Tāne's Tree
//    Trust restoration guidance, and Metcalf's *The Cultivation of New Zealand
//    Native Plants*. Labelled as estimates by each row's `confidence`.
//
// **Common names are the everyday ones, and here that is te reo Māori.**
// Pōhutukawa, kōwhai, harakeke and kawakawa are what Aucklanders call these
// plants in English too, so `common` carries them with their macrons; the
// English name, where there is one, sits in `nativeNote`.
//
// Like the other region files, this is deliberately data-only and heavily
// commented so a non-programmer can audit any row.

