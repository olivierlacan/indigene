// Seed dataset — Continental France: the centre and east (the EEA *Continental*
// biogeographical region), using Burgundy, Lorraine, Alsace and the Rhône
// corridor — Dijon, Nancy, Strasbourg, Lyon — as the reference. Third European
// region, third of the France cluster.
//
// What sets it apart from the Atlantic west is the swing: colder winters (a
// hard −15 °C is normal in Alsace, where the Atlantic coast barely freezes) and
// hotter, drier summers. The flora is the broadleaf woodland and limestone
// grassland of central Europe — beech, hornbeam, lime, wild service tree, and
// the chalk-meadow herbs that carry most of France's butterflies.
//
// Numbers and their provenance — same honesty bar as every other region file:
//  - hostLepCount: a genus-level count of Lepidoptera (butterflies & moths)
//    that use the plant as a larval host, **computed, not estimated** — counted
//    from the Gaytán et al. 2026 species-level European Lepidoptera–plant
//    interaction matrix (CC-BY 4.0, doi:10.1002/ece3.73004), which records
//    larval host associations rather than adult nectar visits. Two filters
//    decide who counts, and both are arguable, which is why each row's `basis`
//    names the figure and, where the filters disagree, the number you'd get
//    without them:
//      1. counted at *genus* level, because the US regions carry genus-level
//         Tallamy figures and the shared HOST_ANCHOR only means something if
//         both sides are on one scale;
//      2. counting only relatives that grow in **continental-temperate** Europe
//         and are native to it — so native hops aren't credited with
//         caterpillars recorded on an introduced relative.
//    Regenerate with `npm run host-counts -- --region france-continental`,
//    which reports what each row should say without rewriting this file. The
//    numbers it reads live in data/sources/eu-lep-plant-matrix/host-counts.json.
//    See docs/host-counts-plan.md.
//  - size arrays: typical field growth on an average Continental-France site;
//    mature*Ft is the honest eventual ceiling, often far larger than nursery
//    tags admit. Kept in feet for now — metric units land with the localization
//    work, not this region.
//  - other scores (0–100): informed estimates from French floras and
//    conservation sources — Tela Botanica (BDTFX), the INPN (MNHN), the
//    Conservatoires botaniques nationaux, and the central-European woodland and
//    calcareous-grassland literature. Native status is asserted for
//    metropolitan France via Tela Botanica and the INPN. See DATA_SOURCES.md
//    for licensing of each upstream source.
//
