// Seed dataset — the Kantō Plain, using Tokyo (≈USDA 9a) as the reference and
// the inland plain at Utsunomiya (8b) as the cold end. This is Japan's largest
// plain: the bay shore at Tokyo and Yokohama, east across Chiba to Chōshi,
// north over Saitama and Tsukuba to Mito and Utsunomiya.
//
// **The flora this list is really about is the satoyama** — the worked country
// between the village and the mountain, coppiced oak and chestnut over a swept
// floor, kept open for charcoal, firewood and mushroom logs for a thousand
// years. It is not wilderness and it is not a garden, and almost everything a
// Kantō gardener thinks of as a wildflower is a plant of that managed edge.
// Where a row names a habitat, that is usually the one it means.
//
// **Every row is checked against Kew's World Checklist of Vascular Plants.**
// `npm run native:check -- --region kanto` asks WCVP whether the plant is native
// in `TDWG:JAP`, which is the whole country — the same grain Ireland (`TDWG:IRE`)
// and Auckland (`TDWG:NZN`) already ship on, and coarser than this region. Two
// candidates fell out on the way and are **not** here: WCVP calls yamaguwa
// (`Morus australis`) and chigaya (`Imperata cylindrica`) introduced in Japan,
// however Japanese they feel.
//
// Because the national grain cannot tell the Kantō from Kyushu, each row's
// `nativeNote` says where on this plain the plant actually grows, and that part
// is editorial rather than machine-checked.
//
// Numbers and their provenance:
//  - hostLepCount: distinct Lepidoptera species recorded on the plant's genus in
//    Japan, from HOSTS — the Natural History Museum's world database of
//    Lepidoptera host plants (CC0), counted in
//    `data/sources/hosts/genus-counts.json`. **Field records only**: HOSTS flags
//    some rearings as laboratory work, and a moth offered a leaf in a jar is
//    weaker evidence than one found on it, so the genus `labOnly` tally is
//    subtracted. Oak is 531 here, not the 561 a raw count gives.
//    Where HOSTS also names the exact species, `basis` gives that narrower
//    figure, because it is the stronger claim — konara's own 272.
//    A genus HOSTS has no Japanese record for takes `null`, never 0: 0 would
//    claim nothing feeds on the plant, and the pages print it as one.
//  - size arrays: typical growth on an average plain site, open ground;
//    mature*Ft is the honest eventual ceiling.
//  - other scores (0–100): informed estimates. Japan has no USDA PLANTS or
//    Xerces equivalent we can read, so these are weaker than the American
//    regions' and are marked by a lower confidence where it matters.
//
// Deliberately data-only and heavily commented so a non-programmer can audit any
// row. A solid *starter* list for the region, not exhaustive.
