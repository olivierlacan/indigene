// Seed dataset — the French Alps: the montane and subalpine belts of the EEA
// *Alpine* biogeographical region, using Grenoble, Annecy, Chambéry, Gap and
// Briançon and the valleys above them as the reference. Fourth European region,
// and the one that completes the France cluster.
//
// A mountain list is a different kind of list. The limiting factors are cold, a
// short growing season and a long snow cover, not summer drought — so what
// belongs here is the flora of spruce and larch forest, alpine pasture and
// rocky ground, most of it low, slow and very long-lived. Altitude matters more
// than latitude: a garden at 1,600 m in the Oisans and one at 400 m in the
// Grésivaudan are different worlds, and the hardiness range on each row covers
// the montane–subalpine band this list is tuned to.
//
// **One deliberate limit.** The EEA Alpine region in France covers the Pyrenees
// as well as the Alps, but the two floras diverge sharply — the Pyrenees carry
// their own endemics — and this list is honestly only tuned to the Alps. So its
// coverage box is drawn over the Alps alone, and a Pyrenean spot gets "no list
// yet" rather than a plausible-looking wrong answer. A Pyrenean list is its own
// piece of work.
//
// Numbers and their provenance — same honesty bar as every other region file:
//  - hostLepCount: a genus-level count of Lepidoptera (butterflies & moths)
//    that use the plant as a larval host, **computed, not estimated** — counted
//    from the Gaytán et al. 2026 species-level European Lepidoptera–plant
//    interaction matrix (CC-BY 4.0, doi:10.1002/ece3.73004), which records
//    larval host associations rather than adult nectar visits. Two filters
//    decide who counts, and both are arguable, which is why each row's `basis`
//    names the figure and, where the filters disagree, the number you'd get
//    without them:
//      1. counted at *genus* level, because the US regions carry genus-level
//         Tallamy figures and the shared HOST_ANCHOR only means something if
//         both sides are on one scale;
//      2. counting only relatives that grow in the **Mountain** zone of Europe
//         and are native to it — so the alpenrose isn't credited with
//         caterpillars recorded on introduced garden rhododendrons (22, not 40).
//    Regenerate with `npm run host-counts -- --region france-alpine`, which
//    reports what each row should say without rewriting this file. The numbers
//    it reads live in data/sources/eu-lep-plant-matrix/host-counts.json.
//    See docs/host-counts-plan.md.
//  - size arrays: typical field growth in the montane belt; mature*Ft is the
//    honest eventual ceiling. Mountain plants grow slowly — a rowan that would
//    make 20 ft in ten years in Burgundy may take twenty here — and the numbers
//    reflect that. Kept in feet for now; metric units land with the
//    localization work, not this region.
//  - other scores (0–100): informed estimates from French alpine floras and
//    conservation sources — Tela Botanica (BDTFX), the INPN (MNHN), the
//    Conservatoire botanique national alpin, and the Parc national des Écrins /
//    Parc national de la Vanoise species work. Native status is asserted for
//    metropolitan France via Tela Botanica and the INPN. See DATA_SOURCES.md
//    for licensing of each upstream source.
//
// Like the other region files, this is deliberately data-only and heavily
// commented so a non-programmer can audit any row.
