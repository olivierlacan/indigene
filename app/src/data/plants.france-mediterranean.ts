// Seed dataset — Mediterranean France: the hot, dry south (the EEA
// *Mediterranean* biogeographical region), using the Provence–Languedoc coast
// and its immediate hinterland as the reference. This is the second European
// region and the second of the France cluster, after Atlantic France.
//
// It is a genuinely different flora from the Atlantic west, not a warmer
// version of it. The limit here is summer drought, not winter cold: nothing on
// this list expects to be watered in July, several would rot if it were, and
// most are hard-leaved evergreens built to shut down through the dry months and
// grow in the mild, wet winter. That is why so few species are shared with the
// Atlantic file even where the two regions touch.
//
// Numbers and their provenance — same honesty bar as every other region file:
//  - hostLepCount: a genus-level count of Lepidoptera (butterflies & moths)
//    that use the plant as a larval host, **computed, not estimated** — counted
//    from the Gaytán et al. 2026 species-level European Lepidoptera–plant
//    interaction matrix (CC-BY 4.0, doi:10.1002/ece3.73004), which records
//    larval host associations rather than adult nectar visits. Two filters
//    decide who counts, and both are arguable, which is why each row's `basis`
//    names the figure and, where the filters disagree, the number you'd get
//    without them:
//      1. counted at *genus* level, because the US regions carry genus-level
//         Tallamy figures and the shared HOST_ANCHOR only means something if
//         both sides are on one scale;
//      2. counting only relatives that grow in **Mediterranean** Europe and are
//         native to it — so a native maple isn't credited with caterpillars
//         recorded on introduced ornamental ones (78, not 119).
//    Regenerate with `npm run host-counts -- --region france-mediterranean`,
//    which reports what each row should say without rewriting this file. The
//    numbers it reads live in data/sources/eu-lep-plant-matrix/host-counts.json.
//    See docs/host-counts-plan.md.
//  - size arrays: typical field growth on an average Mediterranean-France site;
//    mature*Ft is the honest eventual ceiling, often far larger than nursery
//    tags admit. Kept in feet for now — metric units land with the localization
//    work, not this region.
//  - other scores (0–100): informed estimates from French and Mediterranean
//    floras and conservation sources — Tela Botanica (BDTFX), the INPN (MNHN),
//    the Conservatoire botanique national méditerranéen de Porquerolles, and
//    the Mediterranean garrigue/maquis literature. Native status is asserted
//    for metropolitan France via Tela Botanica and the INPN. See
//    DATA_SOURCES.md for licensing of each upstream source.
//
// Like the other region files, this is deliberately data-only and heavily
// commented so a non-programmer can audit any row.
