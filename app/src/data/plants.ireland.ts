// Seed dataset — Ireland: the whole island, Republic and Northern Ireland
// together, using the Dublin–Cork–Galway lowlands as the reference (roughly
// USDA zones 8b–10a). The EEA puts all of it in the *Atlantic* biogeographical
// region, the same one Atlantic France claims — mild, wet, rarely frozen, and
// almost never hot.
//
// **Ireland's flora is small, and that is the interesting part.** The sea closed
// behind the retreating ice before many European species walked back north, so
// the island has roughly two-thirds of Britain's native vascular plants and far
// fewer than France's. There is no native maple, lime, hornbeam or beech here.
// Sycamore and beech are introductions, however old and settled they look, and
// this list leaves them out. What Ireland does have is oak, birch, hazel, holly,
// willow, rowan, whitethorn and blackthorn — and heath, bog and limestone
// pavement floras that most of Europe would envy.
//
// Numbers and their provenance — same honesty bar as every other region file:
//  - **Native status** is asserted from Kew's World Checklist of Vascular Plants
//    (WCVP, CC BY 4.0), which records native and introduced range by TDWG
//    botanical area; Ireland (`TDWG:IRE`) is one area covering the whole island.
//    `npm run native:check -- --region ireland` re-asks WCVP about every row.
//    This is the first region whose native claim rests on the global backbone
//    rather than a national flora — `DATA_SOURCES.md` has long named WCVP as the
//    way to reach a country with no list of our own, and this is that.
//    **Where WCVP disagrees with Irish botanical opinion, WCVP decides and the
//    row does not ship.** That costs this list the Lusitanian element — the
//    Killarney strawberry tree, Mackay's heath, St Dabeoc's heath — which Irish
//    floras treat as native relics and WCVP records as introduced. Better an
//    absent row than a claim our own cited source contradicts; see
//    `data/sources/wcvp/README.md`.
//  - **hostLepCount** is a genus-level count of Lepidoptera (butterflies and
//    moths) that use the plant as a larval host — **computed, not estimated**,
//    from the Gaytán et al. 2026 European Lepidoptera–plant matrix (CC-BY 4.0,
//    doi:10.1002/ece3.73004), which records larval host associations rather than
//    adult nectar visits. Counted for the *Oceanic temperate* zone, the one
//    Ireland sits in, and only for relatives native to it. Two genera on this
//    list — royal fern and lady fern — have no entry in the matrix at all; their
//    rows say 0 and say why, rather than borrowing a number.
//    Regenerate with `npm run host-counts -- --region ireland`. Numbers live in
//    data/sources/eu-lep-plant-matrix/host-counts.json. See
//    docs/host-counts-plan.md.
//  - **size arrays**: typical field growth on an average Irish site — which is
//    to say wetter and milder than most of Europe, so shrubs put on more and
//    ripen less. mature*Ft is the honest eventual ceiling, usually far larger
//    than a nursery tag admits. Feet for now, like every other region.
//  - **other scores (0–100)**: informed estimates from Irish and British sources
//    — the National Biodiversity Data Centre's pollinator lists, the All-Ireland
//    Pollinator Plan, Teagasc and Woodland Trust/Woodlands of Ireland guidance,
//    and the RHS "Plants for Pollinators" list. Labelled as estimates by each
//    row's `confidence`, the way they are everywhere else.
//
// **Ash and wych elm are deliberately absent.** *Fraxinus excelsior* and
// *Ulmus glabra* are both native, both common once, and both excellent wildlife
// trees — and ash dieback and Dutch elm disease have killed most of them.
// Telling somebody to plant one in a small garden now would be bad advice
// dressed up as a native recommendation, so this list doesn't. Elm costs the
// list a top-30 host genus (126 caterpillar species) and that is the right
// price to pay.
//
// Like the other region files, this is deliberately data-only and heavily
// commented so a non-programmer can audit any row.
